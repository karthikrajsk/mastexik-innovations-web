let cachedLoomMasterMap: Map<string, string> | null = null;

/**
 * Fetch Loom Master list to map loomId -> loomNo
 */
export async function getLoomMasterMap(forceRefresh = false): Promise<Map<string, string>> {
  if (cachedLoomMasterMap && !forceRefresh) return cachedLoomMasterMap;
  const map = new Map<string, string>();
  try {
    const res = await apiService.get("/loom-master?limit=10000");
    const data = Array.isArray(res?.data?.data)
      ? res.data.data
      : Array.isArray(res?.data)
      ? res.data
      : Array.isArray(res)
      ? res
      : [];
    data.forEach((item: any) => {
      const id = String(item.id ?? item.loomId ?? '');
      const loomNo = String(item.loomNo ?? item.loom_no ?? item.name ?? item.loomName ?? '');
      if (id && loomNo) {
        map.set(id, loomNo);
      }
    });
    cachedLoomMasterMap = map;
  } catch (err) {
    console.warn("Error fetching loom master for ID mapping:", err);
  }
  return map;
}

