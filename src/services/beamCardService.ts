/**
 * Save Beam Card data JSON to backend API and localStorage fallback
 */
export async function saveBeamCardData(cardData: BeamCardData): Promise<BeamCardData> {
  const beamNo = cardData.beamDetails.beamNo;
  const payload = {
    beamNo,
    loomNo: cardData.beamDetails.loomNo,
    circleNo: cardData.beamDetails.circleNo,
    status: cardData.beamDetails.status,
    beamCardTypeId: cardData.beamCardTypeId != null ? Number(cardData.beamCardTypeId) : null,
    rollWeight: cardData.rollWeight != null ? Number(cardData.rollWeight) : null,
    rollGlm: cardData.rollGlm != null ? Number(cardData.rollGlm) : null,
    data: cardData
  };

  try {
    const res = await apiService.post('/beam-card/save', payload);
    if (res?.data) {
      const savedData = res.data.data || res.data;
      if (savedData) {
        if (savedData.beamDetails) {
          cardData = {
            ...savedData,
            beamCardTypeId: savedData.beamCardTypeId ?? cardData.beamCardTypeId,
            rollWeight: savedData.rollWeight ?? cardData.rollWeight,
            rollGlm: savedData.rollGlm ?? cardData.rollGlm,
          };
        } else if (savedData.data && typeof savedData.data === 'object') {
          cardData = {
            ...savedData.data,
            id: savedData.id,
            beamCardTypeId: savedData.beamCardTypeId ?? savedData.data.beamCardTypeId ?? cardData.beamCardTypeId,
            rollWeight: savedData.rollWeight ?? savedData.data.rollWeight ?? cardData.rollWeight,
            rollGlm: savedData.rollGlm ?? savedData.data.rollGlm ?? cardData.rollGlm,
          };
        }
      }
    }
  } catch (err) {
    console.warn("API /beam-card/save endpoint fallback to localStorage:", err);
  }

  // Cache in localStorage for offline/client persistence
  try {
    localStorage.setItem(`beam_card_saved_${beamNo}`, JSON.stringify(cardData));
    if (cardData.beamDetails.circleNo) {
      localStorage.setItem(`beam_card_circle_no_${beamNo}`, cardData.beamDetails.circleNo);
    }
  } catch (e) {
    console.warn("Could not save beam card to localStorage:", e);
  }

  fallbackCardStore[beamNo] = { ...cardData };
  return cardData;
}

