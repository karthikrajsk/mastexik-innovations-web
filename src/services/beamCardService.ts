/**
 * Add production record dynamically and recalculate Crimp %
 */
export async function addProductionRecord(beamNo: string, payload: NewProductionPayload): Promise<BeamCardData> {
  try {
    const encodedBeamNo = encodeURIComponent(beamNo);
    const res = await apiService.post(`/beam-card/${encodedBeamNo}/production`, payload);
    if (res?.data) return res.data;
  } catch (err) {
    console.warn("Using fallback local store update:", err);
  }

  let card = fallbackCardStore[beamNo] || (await fetchBeamCardData(beamNo));
  const newProdId = `p-${Date.now()}`;
  
  const effectiveRollLength = payload.isInspected && payload.inspectedMtr !== undefined 
    ? payload.inspectedMtr 
    : payload.rollLength;

  const nextIdx = card.productionDetails.length + 1;
  const newRecord: ProductionDetail = {
    slNo: nextIdx,
    id: newProdId,
    date: payload.date,
    pieceNo: payload.pieceNo,
    doffLength: payload.doffLength || 0,
    rollNo: payload.rollNo || `R-${String(nextIdx).padStart(2, '0')}`,
    rollLength: effectiveRollLength,
    rollWeight: payload.rollWeight,
    rollGlm: payload.rollGlm,
    inspectedMtr: payload.inspectedMtr || effectiveRollLength,
    isInspected: payload.isInspected || false,
    weftDetails: payload.weftMillName && payload.weftLotNo ? [
      { id: `w-${Date.now()}`, date: payload.weftDate || payload.date, millName: payload.weftMillName, lotNo: payload.weftLotNo }
    ] : []
  };

  card.productionDetails.push(newRecord);

  // Recalculate dynamic crimp %
  card.fabricSummary.crimpPercentage = calculateCrimpPercentage(
    Number(card.beamDetails.warpLength),
    card.productionDetails
  );
  card.fabricSummary.totalPieces = card.productionDetails.length;
  card.fabricSummary.totalRollMtrs = Number(
    card.productionDetails.reduce((sum, item) => sum + (Number(item.rollLength) || 0), 0).toFixed(2)
  );
  card.fabricSummary.totalDoffMtrs = card.productionDetails.reduce(
    (sum, item) => sum + (Number(item.doffLength) || 0),
    0
  );

  fallbackCardStore[beamNo] = { ...card };
  return card;
}

/**
 * Update warp waste
 */
export async function updateWarpWaste(beamNo: string, payload: UpdateWastePayload): Promise<BeamCardData> {
  try {
    const encodedBeamNo = encodeURIComponent(beamNo);
    const res = await apiService.post(`/beam-card/${encodedBeamNo}/waste`, payload);
    if (res?.data) return res.data;
  } catch (err) {
    console.warn("Using fallback local waste update:", err);
  }

  let card = fallbackCardStore[beamNo] || (await fetchBeamCardData(beamNo));
  const keyMap: Record<string, "knotting" | "reKnotting" | "roWaste"> = {
    "KNOTTING": "knotting",
    "RE-KNOTTING": "reKnotting",
    "R/O WASTE": "roWaste"
  };

  const targetKey = keyMap[payload.category];
  if (targetKey) {
    card.warpWaste[targetKey] = { kgs: payload.kgs, mtrs: payload.mtrs };
    card.warpWaste.total = {
      kgs: Number((card.warpWaste.knotting.kgs + card.warpWaste.reKnotting.kgs + card.warpWaste.roWaste.kgs).toFixed(2)),
      mtrs: Number((card.warpWaste.knotting.mtrs + card.warpWaste.reKnotting.mtrs + card.warpWaste.roWaste.mtrs).toFixed(2))
    };
  }

  fallbackCardStore[beamNo] = { ...card };
  return card;
}
