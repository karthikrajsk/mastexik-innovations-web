/**
 * Format ISO or raw date string to display format (DD/MM/YY)
 */
export function formatDateDisplay(dateStr?: string): string {
  if (!dateStr || dateStr === '-') return '-';
  
  if (/^\d{1,2}[\/\-]\d{1,2}[\/\-]\d{2,4}$/.test(dateStr.trim())) {
    return dateStr.trim();
  }

  try {
    const d = new Date(dateStr);
    if (isNaN(d.getTime())) return dateStr;
    const day = d.getDate();
    const month = d.getMonth() + 1;
    const yearStr = d.getFullYear().toString().slice(-2);
    return `${day}/${month}/${yearStr}`;
  } catch {
    return dateStr;
  }
}

/**
 * Dynamic Crimp % Calculation Logic:
 * Crimp % = ((WARP LENGTH - SUM(DOFF LENGTH)) / SUM(DOFF LENGTH)) * 100
 */
export function calculateCrimpPercentage(warpLength: number, productionDetails: ProductionDetail[]): string {
  const sumDoffLength = productionDetails.reduce(
    (sum, p) => sum + (Number(p.doffLength) || 0),
    0
  );

  if (!warpLength || sumDoffLength <= 0) {
    return "0.00%";
  }

  const crimpVal = ((warpLength - sumDoffLength) / sumDoffLength) * 100;
  return `${crimpVal.toFixed(2)}%`;
}

/**
 * Helper to get autogenerated circle document number for Beam Card header badge
 */
export async function getAutogeneratedCircleNo(existingNo?: string, beamNo?: string): Promise<string> {
  // Ignore legacy static placeholders "26", "2160", "Unknown"
  if (existingNo && existingNo !== "26" && existingNo !== "2160" && existingNo !== "Unknown" && existingNo.trim() !== "") {
    return existingNo;
  }

  if (beamNo) {
    // 1. Check localStorage for persistent assigned circleNo (ignoring legacy "26" / "2160")
    try {
      const storedCircle = localStorage.getItem(`beam_card_circle_no_${beamNo}`);
      if (storedCircle && storedCircle !== "26" && storedCircle !== "2160" && storedCircle !== "Unknown") {
        return storedCircle;
      }
    } catch (e) {
      // ignore
    }

    // 2. Find position in active Beam Gaiting list to generate sequential padded number: 001, 002, 003...
    try {
      const beams = await fetchBeamsList();
      const bIdx = beams.findIndex(b => b.beamNo === beamNo || b.id === beamNo || String(b.beamNo).includes(beamNo) || String(beamNo).includes(String(b.beamNo)));
      if (bIdx !== -1) {
        const seqVal = String(bIdx + 1).padStart(3, '0'); // 001, 002, 003...
        try { localStorage.setItem(`beam_card_circle_no_${beamNo}`, seqVal); } catch (e) {}
        return seqVal;
      }
    } catch (e) {
      // ignore
    }
  }

  // 3. Document Number Service sequence
  try {
    const res = await documentNumberService.generateDocumentNumber({ screenName: "Beam Card" });
    if (res?.documentNumber) {
      const match = res.documentNumber.match(/\d+/);
      const val = match ? String(Number(match[0])).padStart(3, '0') : res.documentNumber;
      if (beamNo && val) {
        try { localStorage.setItem(`beam_card_circle_no_${beamNo}`, val); } catch (e) {}
      }
      return val;
    }
  } catch (err) {
    console.warn("Could not fetch autogenerated document number:", err);
  }

  // 4. Sequential counter fallback in localStorage for new beam entries
  if (beamNo) {
    let nextSeq = 1;
    try {
      const savedCounter = localStorage.getItem("beam_card_circle_counter");
      if (savedCounter && !isNaN(Number(savedCounter))) {
        nextSeq = Number(savedCounter);
      }
      const seqVal = String(nextSeq).padStart(3, '0');
      localStorage.setItem(`beam_card_circle_no_${beamNo}`, seqVal);
      localStorage.setItem("beam_card_circle_counter", String(nextSeq + 1));
      return seqVal;
    } catch (e) {
      // ignore
    }

    let hash = 0;
    for (let i = 0; i < beamNo.length; i++) {
      hash = ((hash << 5) - hash) + beamNo.charCodeAt(i);
      hash |= 0;
    }
    const num = (Math.abs(hash) % 999) + 1;
    const generated = String(num).padStart(3, '0');
    try { localStorage.setItem(`beam_card_circle_no_${beamNo}`, generated); } catch (e) {}
    return generated;
  }

  return "001";
}


